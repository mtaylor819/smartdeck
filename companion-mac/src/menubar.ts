import { chmodSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

export const PLUGIN_FILENAME = 'smartdeck.10s.sh';

/** Paths end up inside a bash script and SwiftBar `key="value"` params: refuse anything that would break either. */
function checkPath(label: string, p: string): void {
  if (!p || /[\r\n\0|"]/.test(p)) throw new Error(`${label} contains a character that is not allowed in a menu-bar plugin (newline, |, ")`);
}

const bashSingle = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

/**
 * SwiftBar/xbar plugin (bash). ASSUMPTIONS (from memory, UNVERIFIED on a real Mac):
 *  - the filename's middle part ("10s") is the refresh interval;
 *  - stdout lines before the first `---` form the menu-bar title; each later line is a menu item;
 *  - parameters follow ` | `, as `key=value`; values with spaces are double-quoted;
 *  - `shell=<exe> param1=.. param2=..` runs a command, `terminal=false` hides Terminal, `refresh=true` re-runs the plugin;
 *  - `href=<url>` opens a URL.
 * It expects the CLI to provide `status --short` (one line, e.g. "● Smart Deck (USB)").
 */
export function swiftbarPluginSource(opts: { nodePath: string; cliPath: string }): string {
  checkPath('nodePath', opts.nodePath);
  checkPath('cliPath', opts.cliPath);
  const node = opts.nodePath;
  const cli = opts.cliPath;
  const q = (s: string) => `"${s}"`;
  const run = (label: string, ...params: string[]) =>
    `${label} | shell=${q(node)} ${[cli, ...params].map((p, i) => `param${i + 1}=${q(p)}`).join(' ')} terminal=false refresh=true`;

  return `#!/bin/bash
# <xbar.title>SmartDeck</xbar.title>
# <xbar.desc>SmartDeck status and quick actions</xbar.desc>
# <swiftbar.hideAbout>true</swiftbar.hideAbout>
# Generated by smartdeck-mac. Re-generate with: smartdeck-mac install-menubar
NODE=${bashSingle(node)}
CLI=${bashSingle(cli)}
STATUS="$("$NODE" "$CLI" status --short 2>/dev/null | head -n 1)"
[ -z "$STATUS" ] && STATUS="○ SmartDeck (daemon not running)"
echo "$STATUS"
echo "---"
cat <<'MENU'
Open SmartDeck UI | href=http://127.0.0.1:7777/
---
${run('Red alert (30s)', 'alert', 'red', '30', 'Red alert')}
${run('Yellow alert (30s)', 'alert', 'yellow', '30')}
${run('Blue notice (10s)', 'alert', 'blue', '10')}
${run('Clear alert', 'alert', 'off')}
---
${run('Sync to deck', 'sync')}
MENU
printf 'Restart service | shell=/bin/launchctl param1=kickstart param2=-k param3="gui/%s/com.smartdeck.mac" terminal=false refresh=true\\n' "$(id -u)"
printf 'Open log | shell=/usr/bin/open param1="%s/Library/Logs/smartdeck-mac.log" terminal=false\\n' "$HOME"
`;
}

export type Runner = (file: string, args: string[]) => Promise<string>;
export interface DirFs {
  existsSync(p: string): boolean;
}

/** Where SwiftBar (or xbar) looks for plugins. Order: SwiftBar preference, SwiftBar default, xbar default. */
export async function findSwiftbarPluginDir(
  run: Runner,
  fs: DirFs = { existsSync },
  home: string = homedir(),
): Promise<string | undefined> {
  try {
    const out = (await run('defaults', ['read', 'com.ameba.SwiftBar', 'PluginDirectory'])).trim();
    if (out && fs.existsSync(out)) return out;
  } catch {
    /* SwiftBar not configured */
  }
  const candidates = [
    join(home, 'Library', 'Application Support', 'SwiftBar', 'Plugins'),
    join(home, 'Library', 'Application Support', 'xbar', 'plugins'),
  ];
  for (const d of candidates) if (fs.existsSync(d)) return d;
  return undefined;
}

export interface WriteFs {
  mkdirSync(p: string, o?: { recursive: boolean }): unknown;
  writeFileSync(p: string, data: string, o?: { mode: number }): unknown;
  chmodSync(p: string, mode: number): unknown;
}

/** Write the plugin into `dir` (mode 0755) and return its path. */
export function installSwiftbarPlugin(
  dir: string,
  source: string,
  fs: WriteFs = { mkdirSync, writeFileSync, chmodSync },
): string {
  fs.mkdirSync(dir, { recursive: true });
  const file = join(dir, PLUGIN_FILENAME);
  fs.writeFileSync(file, source, { mode: 0o755 });
  fs.chmodSync(file, 0o755); // writeFileSync's mode is ignored when the file already exists
  return file;
}
