#!/usr/bin/env python3
"""Convert a TTF into anti-aliased (4-bit alpha) bitmap fonts for the deck's LCARS UI (needs Pillow).

  python3 -I firmware/tools/genfont.py   # rewrites JC8048W550/Arduino/smart_deck/lcars_font.h

Font: Antonio (SIL OFL, firmware/tools/fonts/OFL-Antonio.txt): SemiBold for the UI, Light for the clock. ASCII 0x20-0x7E.
Glyph bitmaps are row-major 4-bit coverage, two pixels per byte (high nibble first), each glyph byte-aligned.
The firmware blends them onto a known background colour (lcDraw() in smart_deck.ino).
"""
import pathlib
from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
TTF = ROOT / "firmware/tools/fonts/Antonio[wght].ttf"      # variable font: weight axis 100..700
UI_WEIGHT = 600
CLOCK_TTF = TTF
CLOCK_WEIGHT = 300
CLOCK_PX = 70
CLOCK_CHARS = "0123456789:"
OUT = ROOT / "JC8048W550/Arduino/smart_deck/lcars_font.h"
SIZES = [13, 16, 19, 22, 27, 33]   # Antonio cap height is ~0.85 em: these match the earlier cap heights 11..28
FIRST, LAST = 0x20, 0x7E


def build(px, ttf=TTF, only=None, weight=UI_WEIGHT):
    font = ImageFont.truetype(str(ttf), px)
    font.set_variation_by_axes([weight])
    bitmap, glyphs = bytearray(), []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        if only is not None and ch not in only:
            glyphs.append((len(bitmap), 0, 0, 0, 0, 0))
            continue
        adv = int(round(font.getlength(ch)))
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = r - l, b - t
        off = len(bitmap)
        if w > 0 and h > 0 and ch != " ":
            img = Image.new("L", (w + 4, h + 4), 0)
            ImageDraw.Draw(img).text((-l + 2, -t + 2), ch, font=font, fill=255, anchor="ls")
            img = img.crop((2, 2, 2 + w, 2 + h))
            px_ = [img.getpixel((x, y)) >> 4 for y in range(h) for x in range(w)]
            if len(px_) % 2:
                px_.append(0)
            for i in range(0, len(px_), 2):
                bitmap.append((px_[i] << 4) | px_[i + 1])
        else:
            w = h = l = t = 0
        glyphs.append((off, w, h, adv, l, t))
    hl, ht, hr, hb = font.getbbox("H", anchor="ls")
    return bitmap, glyphs, hb - ht


out = ["// GENERATED by firmware/tools/genfont.py from Antonio (SIL OFL). Do not edit.",
       "#pragma once", "#include <Arduino.h>", "",
       "struct LcGlyph { uint32_t off; uint8_t w, h, adv; int8_t xo, yo; };  // yo: top of bitmap relative to baseline",
       "struct LcFont { const uint8_t* bm; const LcGlyph* g; uint8_t cap; uint8_t px; };  // glyphs cover 0x20..0x7E", ""]
names = []
for px in SIZES:
    bm, gl, cap = build(px)
    n = f"LcF{px}"
    names.append((n, px, cap))
    out.append(f"static const uint8_t {n}Bm[] PROGMEM = {{")
    for i in range(0, len(bm), 24):
        out.append("  " + ",".join(f"0x{b:02X}" for b in bm[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const LcGlyph {n}G[] PROGMEM = {{")
    out.append("  " + ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in gl))
    out.append("};")
out.append("static const LcFont LC_FONTS[] = {")
for n, px, cap in names:
    out.append(f"  {{ {n}Bm, {n}G, {cap}, {px} }},")
out.append("};")
out.append(f"static const int LC_NFONTS = {len(names)};")
# Large light-weight clock face (digits and colon only; other glyphs are empty)
bm, gl, cap = build(CLOCK_PX, CLOCK_TTF, CLOCK_CHARS, CLOCK_WEIGHT)
out.append("static const uint8_t LcClockBm[] PROGMEM = {")
for i in range(0, len(bm), 24):
    out.append("  " + ",".join(f"0x{b:02X}" for b in bm[i:i + 24]) + ",")
out.append("};")
out.append("static const LcGlyph LcClockG[] PROGMEM = {")
out.append("  " + ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in gl))
out.append("};")
out.append(f"static const LcFont LC_CLOCK = {{ LcClockBm, LcClockG, {cap}, {CLOCK_PX} }};")
OUT.write_text("\n".join(out) + "\n")
print("wrote", OUT, OUT.stat().st_size, "bytes;", ", ".join(f"{px}px cap {cap}" for _, px, cap in names))
