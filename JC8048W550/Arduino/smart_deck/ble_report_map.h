// ble_report_map.h -- the BLE HID report map as pure data (no Arduino/NimBLE types) so it can be unit-tested on a PC.
// Keyboard (report ID 1): 1 modifier byte, 1 reserved, 6-key array, 5 LED output bits. Consumer control (report ID 2): one 16-bit usage.
//
// v4: the 6-key array's Logical/Usage Maximum is 0xE7 (was 0x65), so F13-F24 (usages 0x68..0x73) are inside the declared range and
// hosts that validate array elements against the descriptor accept them. NOTE: this changes the report map, so hosts that cached the
// old one must forget the deck and pair again (the firmware also purges its own bonds once, see ble_pairing.h BLE_SECURITY_VERSION).
#ifndef BLE_REPORT_MAP_H
#define BLE_REPORT_MAP_H
#include <stdint.h>

static const uint8_t BLE_REPORT_MAP[] = {
  0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, 0x01,          // Usage Page (Generic Desktop), Usage (Keyboard), Collection, Report ID 1
  0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01,
  0x75, 0x01, 0x95, 0x08, 0x81, 0x02,                      // 8 modifier bits (Input)
  0x95, 0x01, 0x75, 0x08, 0x81, 0x01,                      // reserved byte
  0x95, 0x05, 0x75, 0x01, 0x05, 0x08, 0x19, 0x01, 0x29, 0x05, 0x91, 0x02,  // 5 LED bits (Output)
  0x95, 0x01, 0x75, 0x03, 0x91, 0x01,                      // LED padding
  0x95, 0x06, 0x75, 0x08, 0x15, 0x00,
  0x26, 0xE7, 0x00,                                        // Logical Maximum (0x00E7): 2-byte form, a 1-byte 0xE7 would read as signed -25
  0x05, 0x07, 0x19, 0x00, 0x29, 0xE7, 0x81, 0x00,          // 6 key slots (Input, array), Usage Maximum 0xE7
  0xC0,
  0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01, 0x85, 0x02,          // Usage Page (Consumer), Usage (Consumer Control), Report ID 2
  0x15, 0x00, 0x26, 0xFF, 0x03, 0x19, 0x00, 0x2A, 0xFF, 0x03,
  0x75, 0x10, 0x95, 0x01, 0x81, 0x00,                      // one 16-bit usage (Input, array)
  0xC0
};

#endif
